def _q(d, pole, text, opts, reverse=False):
    item = {
        "d": d,
        "pole": pole,
        "q": text,
        "o": [{"t": t, "s": s} for t, s in zip(opts, (2, 1, 0))],
    }
    if reverse:
        item["reverse"] = True
    return item


def _pack_dim(d, pole, rows):
    """rows: list of (question, [opt_high, opt_mid, opt_low]) toward pole.
    Every 3rd item is reverse:true with linguistically flipped option order;
    scores remain [2,1,0] in that display order.
    """
    out = []
    for i, (text, opts) in enumerate(rows):
        reverse = (i + 1) % 3 == 0
        if reverse:
            display = list(reversed(opts))
        else:
            display = opts
        out.append(_q(d, pole, text, display, reverse=reverse))
    return out


