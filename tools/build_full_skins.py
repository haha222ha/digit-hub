def strip_js_comments(s: str) -> str:
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    s = re.sub(r"(?m)^\s*//.*?$", "", s)
    return s


def js_literal_to_py(s: str):
    """Convert simple JS object/array literals (single-quoted strings) to Python via JSON."""
    s = strip_js_comments(s)
    s = re.sub(r",\s*([}\]])", r"\1", s)
    s = re.sub(r"([{\[,]\s*)([A-Za-z_][A-Za-z0-9_]*)\s*:", r'\1"\2":', s)
    s = s.replace("'", '"')
    return json.loads(s)


def extract_mental():
    html = SRC_MENTAL.read_text(encoding="utf-8")
    m = re.search(r"const questions = (\[.*?\]);\s*\n\s*//", html, re.S)
    if not m:
        m = re.search(r"const questions = (\[.*?\]);", html, re.S)
    qs = js_literal_to_py(m.group(1))

    m2 = re.search(r"const roleSpecific = (\{.*?\});\s*\n\s*//", html, re.S)
    roles = js_literal_to_py(m2.group(1))

    m3 = re.search(r"const levels = (\[.*?\]);\s*\n\s*//", html, re.S)
    levels = js_literal_to_py(m3.group(1))
    return qs, roles, levels


