/**
 * Scene narratives — convert type/dims into life-scene paragraphs worth paying for.
 */

function topAndLow(skin, r) {
  if (!r?.pct || !skin?.dimensions) return { tops: [], lows: [] };
  if (r.mode === "mbti") {
    const pairs = [
      { id: "EI", label: r.pct.EI >= 50 ? "外向" : "内向", v: Math.max(r.pct.EI, 100 - r.pct.EI) },
      { id: "SN", label: r.pct.SN >= 50 ? "直觉" : "实感", v: Math.max(r.pct.SN, 100 - r.pct.SN) },
      { id: "TF", label: r.pct.TF >= 50 ? "思考" : "情感", v: Math.max(r.pct.TF, 100 - r.pct.TF) },
      { id: "JP", label: r.pct.JP >= 50 ? "判断" : "感知", v: Math.max(r.pct.JP, 100 - r.pct.JP) },
    ].sort((a, b) => b.v - a.v);
    return { tops: pairs.slice(0, 2), lows: pairs.slice(-1) };
  }
  const ranked = [...skin.dimensions]
    .map((d) => ({ id: d.id, label: d.label, v: r.pct[d.id] || 0 }))
    .sort((a, b) => b.v - a.v);
  return { tops: ranked.slice(0, 2), lows: ranked.slice(-1) };
}

