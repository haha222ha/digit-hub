/** Full unlocked scenes with action lines. */
export function buildScenes(skin, r) {
  const { tops, lows } = topAndLow(skin, r);
  if (r.mode === "mbti") return mbtiScenes(r, tops);
  if (r.mode === "mental_age") return ageScenes(r, tops, lows);
  if (r.mode === "score_bands") return bandScenes(r, tops, lows);
  if (r.mode === "holland") return hollandScenes(r, tops);
  const key = r.type?.replace(/主导$/, "") || "";
  return SIN_SCENES[key] || SIN_SCENES[r.type] || sceneTeasers(skin, r).map((s) => ({ ...s, act: "选一个场景，本周只做一个可勾选动作。" }));
}

export function scenesHtml(skin, r, { unlocked, full = false } = {}) {
  const list = full && unlocked ? buildScenes(skin, r) : sceneTeasers(skin, r);
  return `
    <div class="scene-grid">
      <p class="group-label">${full && unlocked ? "场景翻译 · 可执行" : "场景价值预告"}</p>
      <p class="muted scene-lead">${
        full && unlocked
          ? "把标签翻译成生活场景，并附带一句本周可做的行动。"
          : "解锁后可读完整段落与行动句——这是完整报告最值钱的部分。"
      }</p>
      ${list
        .map(
          (s) => `
        <article class="scene-card ${unlocked || !full ? "" : "locked"} ${full && unlocked ? "scene-card-full" : ""}">
          <h3>${s.h}</h3>
          <p>${s.p}</p>
          ${full && unlocked && s.act ? `<p class="scene-act"><strong>本周动作</strong> ${s.act}</p>` : ""}
          ${!unlocked && !full ? `<span class="scene-lock">完整解读待解锁</span>` : ""}
        </article>`
        )
        .join("")}
    </div>
  `;
}
