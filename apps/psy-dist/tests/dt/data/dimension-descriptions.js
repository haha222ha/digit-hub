/**
 * 根据维度和得分生成描述
 */
export function getDimensionDescription(dimKey, avgScore) {
  const descriptions = DIMENSION_DESCRIPTIONS[dimKey];
  if (!descriptions) {
    return `您在${dimKey}维度上得分${avgScore.toFixed(2)}/5.00。`;
  }
  
  // 根据得分范围选择描述
  if (avgScore >= 3.5) {
    return descriptions.high(avgScore);
  } else if (avgScore >= 2.5) {
    return descriptions.medium(avgScore);
  } else {
    return descriptions.low(avgScore);
  }
}

